import type {
  ChatMessage,
  ModelClient,
  ModelRequest,
  ModelResponse,
  ToolCall,
} from '@orchestrate/model';

export interface DeterministicTestModelClientOptions {
  shouldFailVerification?: boolean;
}

/**
 * Deterministic, offline ModelClient for testing Orchestrate agent orchestration
 * without external network calls, API keys, or financial token usage.
 */
export class DeterministicTestModelClient implements ModelClient {
  private callCount = 0;
  private readonly shouldFailVerification: boolean;

  constructor(options: DeterministicTestModelClientOptions = {}) {
    this.shouldFailVerification = Boolean(options.shouldFailVerification);
  }

  async complete(request: ModelRequest): Promise<ModelResponse> {
    this.callCount++;
    const messages = request.messages;
    const lastMessage = messages[messages.length - 1];

    // Check if the user prompt explicitly requested a failed verification or if configured
    const userPrompt = messages.find((m) => m.role === 'user')?.content ?? '';
    const isIntentionalFailure =
      this.shouldFailVerification ||
      userPrompt.includes('FAIL_VERIFICATION') ||
      userPrompt.includes('intentional_fail');

    // Planner role handler
    if (request.model === 'zai-org/GLM-5.3-Flash' || userPrompt.startsWith('You are the Lead Planning Agent')) {
      return {
        id: `test-plan-${this.callCount}`,
        provider: 'nebius',
        model: 'zai-org/GLM-5.3-Flash',
        finishReason: 'stop',
        message: {
          role: 'assistant',
          content: JSON.stringify({
            summary: 'Structured plan generated by Lead Planning Agent (GLM-5.3-Flash)',
            targetFiles: ['src/feature.js'],
            acceptanceCriteria: ['Feature implementation satisfies task objective', 'Verification suite passes'],
            implementationSteps: ['Inspect repository state', 'Apply code edits with write_file', 'Run checks'],
            risks: ['Preserve backward compatibility'],
          }),
        },
        usage: { promptTokens: 80, completionTokens: 60, totalTokens: 140 },
      };
    }

    // Reviewer role handler
    if (request.model === 'nvidia/Nemotron-3.5-Super-VL' || userPrompt.startsWith('You are the Independent Code Reviewer')) {
      return {
        id: `test-review-${this.callCount}`,
        provider: 'nebius',
        model: 'nvidia/Nemotron-3.5-Super-VL',
        finishReason: 'stop',
        message: {
          role: 'assistant',
          content: JSON.stringify({
            verdict: isIntentionalFailure ? 'REQUEST_CHANGES' : 'APPROVED',
            summary: isIntentionalFailure
              ? 'Independent Reviewer flagged verification issues in captured diff.'
              : 'Independent Reviewer verified code diff against requirements. No regressions detected.',
            findings: isIntentionalFailure ? ['Intentional error detected in code'] : ['Clean implementation without unused imports'],
            potentialRegressions: [],
          }),
        },
        usage: { promptTokens: 90, completionTokens: 40, totalTokens: 130 },
      };
    }

    // 1. First model call: issue tool call to write implementation file if tools are present
    const hasToolResult = messages.some((m) => m.role === 'tool');

    if (!hasToolResult && request.tools && request.tools.length > 0) {
      const writeFileTool = request.tools.find((t) => t.name === 'write_file');
      if (writeFileTool) {
        // Determine file path from task prompt or use default
        let targetFile = 'src/feature.js';
        const fileMatch = userPrompt.match(/(?:in|to|file|create)\s+([a-zA-Z0-9_\-./]+\.[a-zA-Z0-9]+)/i);
        if (fileMatch && fileMatch[1]) {
          targetFile = fileMatch[1];
        }

        let fileContent = isIntentionalFailure
          ? '// Intentional verification failure implementation\nexport function run() { throw new Error("Intentional acceptance test failure"); }\n'
          : `// Verified implementation generated by Orchestrate Agent\nexport function execute() {\n  return { success: true, timestamp: "${new Date().toISOString()}" };\n}\n`;

        if (targetFile.includes('calculator') || userPrompt.includes('calculator') || userPrompt.includes('add(a, b)')) {
          fileContent = isIntentionalFailure
            ? 'export function add(a, b) { throw new Error("Intentional calc failure"); }\n'
            : 'export function add(a, b) {\n  return a + b;\n}\n';
        }

        const toolCalls: ToolCall[] = [
          {
            id: `call_${Date.now()}_1`,
            name: 'write_file',
            arguments: {
              path: targetFile,
              content: fileContent,
            },
          },
        ];

        return {
          id: `test-resp-${this.callCount}`,
          provider: 'nebius',
          model: request.model || 'deterministic-test-model',
          finishReason: 'tool_calls',
          message: {
            role: 'assistant',
            content: 'Writing required implementation to workspace...',
            toolCalls,
          },
          usage: {
            promptTokens: 120,
            completionTokens: 40,
            totalTokens: 160,
          },
        };
      }
    }

    // 2. Second model call (or if no tools): produce structured handoff
    const handoffJson = JSON.stringify(
      {
        summary: isIntentionalFailure
          ? 'Completed task with intentional failure state for testing verification rejection.'
          : 'Completed task implementation and confirmed file structure.',
        changes: isIntentionalFailure
          ? 'Added code that intentionally throws during acceptance tests.'
          : 'Created/modified required source files in accordance with task specification.',
        filesAffected: ['src/feature.js'],
        decisionsCreated: [],
        assumptions: ['Runtime environment supports ES modules.'],
        limitations: [],
        recommendedFollowUp: ['Run automated verification suite.'],
      },
      null,
      2
    );

    return {
      id: `test-resp-${this.callCount}`,
      provider: 'nebius',
      model: request.model || 'deterministic-test-model',
      finishReason: 'stop',
      message: {
        role: 'assistant',
        content: `I have completed the task in the workspace.\n\n\`\`\`json\n${handoffJson}\n\`\`\``,
      },
      usage: {
        promptTokens: 150,
        completionTokens: 85,
        totalTokens: 235,
      },
    };
  }

  async listModels(): Promise<string[]> {
    return ['deterministic-test-model', 'nvidia/NVIDIA-Nemotron-3-Nano-30B-A3B'];
  }
}
